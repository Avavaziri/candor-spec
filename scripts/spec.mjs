// Usage: node scripts/spec.mjs check | checklist
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const DOCS = 'docs'
const AREAS = [
  ['uncertainty', 'Uncertainty', 'UNC'],
  ['injection', 'Injection warnings', 'INJ'],
  ['privacy', 'Privacy boundaries', 'PRV'],
  ['citing', 'Verifiable citing', 'CIT']
]
const SECTIONS = [
  'Summary', 'Problem', 'When to use', 'When not to use', 'Anatomy', 'Requirements', 'Wording',
  'Accessibility', 'Security and privacy considerations', 'Anti-patterns', 'Demo',
  'Conformance checklist', 'Prior art'
]

function loadPatterns() {
  const patterns = []
  for (const [dir, areaName, prefix] of AREAS) {
    const files = readdirSync(join(DOCS, 'patterns', dir)).filter((f) => f.endsWith('.md')).sort()
    for (const file of files) {
      const path = join(DOCS, 'patterns', dir, file)
      const text = readFileSync(path, 'utf8').replace(/\r\n/g, '\n')
      const fm = Object.fromEntries(
        [...(text.match(/^---\n([\s\S]*?)\n---/)?.[1] ?? '').matchAll(/^(\w+):\s*(.+)$/gm)].map((m) => [m[1], m[2].trim()])
      )
      patterns.push({ path, dir, areaName, prefix, slug: file.replace(/\.md$/, ''), text, fm })
    }
  }
  return patterns.sort((a, b) => AREAS.findIndex((x) => x[0] === a.dir) - AREAS.findIndex((x) => x[0] === b.dir) || num(a) - num(b))
}

const num = (p) => Number(p.fm.id?.split('-')[1] ?? 0)

function section(text, name) {
  const start = text.indexOf(`\n## ${name}\n`)
  if (start < 0) return ''
  const rest = text.slice(start + name.length + 5)
  const end = rest.search(/\n## /)
  return (end < 0 ? rest : rest.slice(0, end)).trim()
}

function check(patterns) {
  const errors = []
  const err = (p, msg) => errors.push(`${p.path}: ${msg}`)
  const seen = new Set()
  for (const p of patterns) {
    const { id, title } = p.fm
    if (!id || !title) { err(p, 'front matter needs id and title'); continue }
    if (!id.startsWith(p.prefix + '-')) err(p, `id ${id} must start with ${p.prefix}-`)
    if (seen.has(id)) err(p, `duplicate id ${id}`)
    seen.add(id)
    if (!p.text.includes(`\n# ${id} ${title}\n`)) err(p, `title must be "# ${id} ${title}"`)
    const headings = [...p.text.matchAll(/^## (.+)$/gm)].map((m) => m[1].trim())
    if (headings.join('|') !== SECTIONS.join('|')) err(p, `sections must be, in order: ${SECTIONS.join(', ')}. Found: ${headings.join(', ')}`)
    for (const name of SECTIONS) if (!section(p.text, name)) err(p, `section "${name}" is empty`)

    const reqs = [...p.text.matchAll(/^::: req ([A-Z]{3}-\d+\.\d+)\n([\s\S]*?)\n:::$/gm)].map((m) => ({ rid: m[1], body: m[2] }))
    if (!reqs.length) err(p, 'no requirements')
    reqs.forEach((r, i) => {
      if (r.rid !== `${id}.${i + 1}`) err(p, `requirement ${r.rid} should be ${id}.${i + 1}`)
    })
    const checklist = section(p.text, 'Conformance checklist')
    const linked = new Set([...checklist.matchAll(/\]\(#([a-z]{3}-\d+\.\d+)\)/g)].map((m) => m[1].toUpperCase()))
    for (const rid of linked) if (!reqs.some((r) => r.rid === rid)) err(p, `checklist links to missing requirement ${rid}`)
    for (const r of reqs) if (/\bMUST\b/.test(r.body) && !linked.has(r.rid)) err(p, `MUST requirement ${r.rid} has no checklist item`)
    for (const r of reqs) if (!/\b(MUST|SHOULD|MAY)\b/.test(r.body)) err(p, `requirement ${r.rid} has no BCP 14 keyword`)
    for (const name of SECTIONS.filter((s) => s !== 'Requirements')) {
      const hit = section(p.text, name).match(/\b(MUST|SHOULD|SHALL|REQUIRED|RECOMMENDED|OPTIONAL)\b|\bMAY\b/)
      if (hit) err(p, `BCP 14 keyword "${hit[0]}" in informative section "${name}"`)
    }
  }
  if (errors.length) {
    console.error(errors.join('\n'))
    process.exit(1)
  }
  console.log(`spec check: ${patterns.length} patterns OK`)
}

function checklist(patterns) {
  const out = [
    '---', "status: Editor's Draft", 'pageClass: checklist-page', '---', '',
    '<!-- Generated by scripts/spec.mjs. Edit the pattern pages, not this file. -->', '',
    '# Conformance checklist', '',
    'Use this checklist to assess an interface against Candor 0.1.',
    'Each check links to the requirement that it tests.',
    'Mark a pattern "not applicable" if the interface does not have the feature that it describes.', ''
  ]
  for (const [dir, areaName] of AREAS) {
    const inArea = patterns.filter((p) => p.dir === dir)
    if (!inArea.length) continue
    out.push(`## ${areaName}`, '')
    for (const p of inArea) {
      const items = section(p.text, 'Conformance checklist').replace(/\]\(#/g, `](./patterns/${dir}/${p.slug}#`)
      out.push(`### [${p.fm.id} ${p.fm.title}](./patterns/${dir}/${p.slug})`, '', items, '')
    }
  }
  writeFileSync(join(DOCS, 'checklist.md'), out.join('\n'))
  console.log(`checklist: ${patterns.length} patterns written to docs/checklist.md`)
}

const mode = process.argv[2]
const patterns = loadPatterns()
if (mode === 'check') check(patterns)
else if (mode === 'checklist') checklist(patterns)
else { console.error('usage: node scripts/spec.mjs check|checklist'); process.exit(2) }
